"""Generates the installable GSC for each game from gsc/ and config/.

dist/<game>/mods/portal_bridge/   Mod Tools layout (compile into mod.ff)
dist/<game>/plutonium/storage/... single-file bundle for Plutonium's loose
                                  script loader, laid out like Plutonium's own
                                  storage folder so it can be copied over it
"""
from __future__ import annotations

import os
import re
import shutil
from pathlib import Path

from .config import GAMES, REPO_ROOT, Config
from .translate import WeaponTranslator

GSC_DIR = REPO_ROOT / "gsc"
MOD_NAME = "portal_bridge"
INCLUDE_RE = re.compile(r"^\s*#include\s+([\w\\]+)\s*;\s*$", re.MULTILINE)

GENERATED_HEADER = "// AUTO-GENERATED by `python -m portal_bridge build` from config/*.json - do not edit.\n"


def gsc_string(value: str) -> str:
    if '"' in value or "\\" in value or "\n" in value:
        raise ValueError(f"can't embed {value!r} in a GSC string")
    return f'"{value}"'


def _gsc_bool(value) -> str:
    return "true" if value else "false"


def installed_map_ids(config: Config, game: str) -> set[str] | None:
    """Map ids whose fastfile (zone/<lang>/<map>.ff) is in the game folder, or
    None when the folder can't be read (then every map is kept)."""
    zone = Path(os.path.expandvars(os.path.expanduser(config.games[game].game_dir))) / "zone"
    if not zone.is_dir():
        return None
    return {p.stem.lower() for p in zone.glob("**/*.ff")}


def missing_maps(config: Config, game: str) -> list[str]:
    """Enabled maps left out of the in-game list because you don't own them."""
    have = installed_map_ids(config, game)
    if have is None:
        return []
    return [m.name for m in config.enabled_maps() if m.game == game and m.id.lower() not in have]


def generate_catalog(config: Config, game: str) -> str:
    gp = config.gameplay
    out = [GENERATED_HEADER, "\n"]
    have = installed_map_ids(config, game)

    out.append("pb_catalog_maps()\n{\n\tlist = [];\n")
    for m in config.enabled_maps():
        if have is not None and m.id.lower() not in have:
            continue  # not owned: a portal to it would fail to load
        label = f"{m.name} ({config.games[m.game].label})"
        out.append(
            f"\tlist[ list.size ] = pb_catalog_map( {gsc_string(m.game)}, "
            f"{gsc_string(m.id)}, {gsc_string(m.name)}, {gsc_string(label)} );\n"
        )
    out.append("\treturn list;\n}\n\n")

    out.append(
        "pb_catalog_map( game_id, id, name, label )\n{\n"
        "\tm = spawnStruct();\n"
        "\tm.game_id = game_id;\n"
        "\tm.id = id;\n"
        "\tm.name = name;\n"
        "\tm.label = label;\n"
        "\treturn m;\n}\n\n"
    )

    ints = [
        "portal_cost", "portal_duration", "portal_distance", "portal_width", "portal_height",
        "portal_fx_points", "enter_radius", "bridge_timeout", "weapon_refund",
    ]
    bools = ["perks_require_machine", "same_game_changelevel", "allow_combo"]
    defaults = {
        "portal_cost": 0, "portal_duration": 90, "portal_distance": 120, "portal_width": 44,
        "portal_height": 80, "portal_fx_points": 24, "enter_radius": 22, "bridge_timeout": 10,
        "weapon_refund": 1000, "perks_require_machine": True, "same_game_changelevel": True,
        "allow_combo": True,
    }
    out.append("pb_catalog_settings()\n{\n\ts = spawnStruct();\n")
    for key in ints:
        out.append(f"\ts.{key} = {int(gp.get(key, defaults[key]))};\n")
    for key in bools:
        out.append(f"\ts.{key} = {_gsc_bool(gp.get(key, defaults[key]))};\n")
    out.append(f"\ts.custom_fx = {gsc_string(gp.get('custom_fx', ''))};\n")
    out.append("\treturn s;\n}\n\n")

    out.append("// Space-separated names for the same weapon within this game.\n")
    out.append("pb_catalog_weapon_aliases()\n{\n\tlist = [];\n")
    for group in WeaponTranslator(config.weapons).aliases(game):
        out.append(f"\tlist[ list.size ] = {gsc_string(' '.join(group))};\n")
    out.append("\treturn list;\n}\n")
    return "".join(out)


ROUTES = ("modtools", "plutonium")

# Where Plutonium loads loose scripts from. raw/scripts/sp loads on every SP map
# (main() skips non-zombie maps); T5's scripts/sp/zom would only load when the
# zombies game mode was picked from the menu, which a direct +devmap launch skips.
PLUTONIUM_SCRIPT_DIRS = {"bo1": "storage/t5/raw/scripts/sp"}
PLUTONIUM_SCRIPTDATA = {"bo1": "storage/t5/raw/scriptdata"}
SIGNAL_FILE = "portal_bridge_travel.txt"

# Stock-script functions the adapters call: (script, function, arg count,
# returns a value). Each becomes a pb_x_<function> wrapper in the platform file.
# Signatures checked against the stock scripts (plutoniummod/t5-scripts):
# add_to_player_score( points, add_to_total ), give_perk( perk, bought ).
STOCK_CALLS = {
    "bo1": [
        ("maps/_zombiemode_score", "add_to_player_score", 2, False),
        ("maps/_zombiemode_score", "minus_to_player_score", 1, False),
        ("maps/_zombiemode_perks", "give_perk", 2, False),
    ],
}


def _stock_wrapper(path: str, func: str, argc: int, returns: bool, route: str) -> str:
    params = ", ".join(f"a{i}" for i in range(argc))
    sig = f"pb_x_{func}( {params} )" if params else f"pb_x_{func}()"
    call_args = f"( {params} )" if params else "()"
    if route == "modtools":
        target = path.replace("/", "\\")
        body = f"\t{'return ' if returns else ''}self {target}::{func}{call_args};\n"
    else:
        body = f'\tf = pb_stock( "{path}", "{func}" );\n'
        if returns:
            body += "\tif( !isDefined( f ) )\n\t\treturn false;\n"
            body += f"\treturn self [[ f ]]{call_args};\n"
        else:
            body += f"\tif( isDefined( f ) )\n\t\tself [[ f ]]{call_args};\n"
    return f"{sig}\n{{\n{body}}}\n"


MODTOOLS_SPAWN = (
    "pb_spawn_model( origin )\n{\n"
    '\tm = spawn( "script_model", origin );\n'
    '\tm setModel( "tag_origin" );\n'
    "\treturn m;\n}\n"
)
# An in-game test found Plutonium T5 rejecting a direct spawn() in
# scripts/sp/zom ("unknown function"), which would stop the map loading; the
# stock maps\_utility::spawn_model helper does the same thing.
PLUTONIUM_T5_SPAWN = (
    "pb_spawn_model( origin )\n{\n"
    '\treturn spawn_model( "tag_origin", origin );\n}\n'
)


def generate_platform(game: str, route: str) -> str:
    """Everything that differs between the Mod Tools build and the Plutonium
    loose-script build."""
    out = [GENERATED_HEADER]
    if route == "modtools":
        out.append(
            "// Mod Tools build: compiled into mod.ff next to the stock scripts.\n\n"
            "// Reaches the bridge through the console log, so the game must run with\n"
            "// developer_script 1 and logfile 1/2 (the bridge's launch arguments set both).\n"
            "pb_emit( line )\n{\n\tprintln( line );\n\treturn true;\n}\n\n"
            + MODTOOLS_SPAWN + "\n"
            "// Keeps frozen players alive while the bridge swaps games.\n"
            "pb_protect( on )\n{\n\tif( on )\n\t\tself EnableInvulnerability();\n"
            "\telse\n\t\tself DisableInvulnerability();\n}\n\n"
            "pb_engine_changelevel( mapname )\n{\n\tchangelevel( mapname, false );\n\treturn true;\n}\n"
        )
    else:
        out.append(
            "// Plutonium build: a loose script, compiled when the game starts. It can't\n"
            "// reference the zombiemode scripts directly (they aren't loaded yet), so\n"
            "// stock functions are looked up by name once a map is running.\n\n"
            "// println doesn't reach any log on Plutonium; its file API writes to\n"
            f"// <Plutonium>/{PLUTONIUM_SCRIPTDATA[game]}/, which the bridge watches.\n"
            "// Fails if that folder is missing or scr_allowFileIo is 0.\n"
            "pb_emit( line )\n{\n"
            f'\tf = fs_fopen( "{SIGNAL_FILE}", "write" );\n'
            "\tif( !isDefined( f ) || !f )\n\t\treturn false;\n"
            "\tfs_writeline( f, line );\n"
            "\tfs_fclose( f );\n"
            "\treturn true;\n}\n\n"
            + (PLUTONIUM_T5_SPAWN if game == "bo1" else MODTOOLS_SPAWN) + "\n"
            "// Uses only builtins known to compile in Plutonium loose scripts, so frozen\n"
            "// players aren't made invulnerable here; the bridge closes the game within\n"
            "// a second or two of the request.\n"
            "pb_protect( on )\n{\n}\n\n"
            "// Same-game trips change the map in place: no restart, no profile check.\n"
            "// ChangeLevel is a stock builtin in both games (used by _endmission).\n"
            "pb_engine_changelevel( mapname )\n{\n\tchangelevel( mapname, false );\n\treturn true;\n}\n\n"
            "pb_stock( path, name )\n{\n"
            "\tif( !isDefined( level.pb_stock ) )\n\t\tlevel.pb_stock = [];\n"
            '\tkey = path + "::" + name;\n'
            "\tif( !isDefined( level.pb_stock[ key ] ) )\n"
            "\t\tlevel.pb_stock[ key ] = getFunction( path, name );\n"
            "\treturn level.pb_stock[ key ];\n}\n"
        )
    out.append("\n// Calls into the stock zombies scripts.\n")
    for path, func, argc, returns in STOCK_CALLS[game]:
        out.append("\n" + _stock_wrapper(path, func, argc, returns, route))
    return "".join(out)


def bundle(sources: list[str]) -> str:
    """Merge core + adapter + catalog into one file for loaders that only take a
    single script: drop the cross-file includes, keep the stock ones."""
    includes: list[str] = []
    bodies: list[str] = []
    for text in sources:
        for inc in INCLUDE_RE.findall(text):
            if "_portal_bridge" not in inc and inc not in includes:
                includes.append(inc)
        bodies.append(INCLUDE_RE.sub("", text).strip("\n"))
    head = "".join(f"#include {inc};\n" for inc in includes)
    return GENERATED_HEADER + head + "\n" + "\n\n".join(bodies) + "\n"


MOD_CSV = """rawfile,maps/_portal_bridge.gsc
rawfile,maps/_portal_bridge_game.gsc
rawfile,maps/_portal_bridge_catalog.gsc
rawfile,maps/_portal_bridge_platform.gsc
rawfile,maps/_zombiemode.gsc
"""

SCRIPTDATA_NOTE = (
    "Portal Bridge: the zombies script writes portal_bridge_travel.txt here when you step\n"
    "through a portal, and the bridge app picks it up. This folder must exist.\n"
)


def _write(path: Path, text: str) -> None:
    # Normalise first so a CRLF checkout doesn't become CR CR LF.
    path.write_text(text.replace("\r\n", "\n"), encoding="utf-8", newline="\r\n")


def build(config: Config, out_dir: Path | str) -> list[Path]:
    out_dir = Path(out_dir)
    written: list[Path] = []
    core = (GSC_DIR / "shared" / "maps" / "_portal_bridge.gsc").read_text(encoding="utf-8")

    for game in GAMES:
        adapter = (GSC_DIR / game / "maps" / "_portal_bridge_game.gsc").read_text(encoding="utf-8")
        catalog = generate_catalog(config, game)

        game_out = out_dir / game
        if game_out.exists():
            shutil.rmtree(game_out)

        mod_maps = game_out / "mods" / MOD_NAME / "maps"
        mod_maps.mkdir(parents=True)
        for name, text in (
            ("_portal_bridge.gsc", core),
            ("_portal_bridge_game.gsc", adapter),
            ("_portal_bridge_catalog.gsc", catalog),
            ("_portal_bridge_platform.gsc", generate_platform(game, "modtools")),
        ):
            path = mod_maps / name
            _write(path, text)
            written.append(path)

        csv = game_out / "mods" / MOD_NAME / "mod.csv"
        _write(csv, MOD_CSV)
        written.append(csv)

        plut_root = game_out / "plutonium"
        plut = plut_root / PLUTONIUM_SCRIPT_DIRS[game] / "portal_bridge.gsc"
        plut.parent.mkdir(parents=True)
        _write(plut, bundle([core, adapter, catalog, generate_platform(game, "plutonium")]))
        written.append(plut)
        note = plut_root / PLUTONIUM_SCRIPTDATA[game] / "portal_bridge_readme.txt"
        note.parent.mkdir(parents=True)
        _write(note, SCRIPTDATA_NOTE)
        written.append(note)

    return written
